FILLED_ICONS = {"whatsapp"}


@register.simple_tag
def icon(name: str, size: int = 16, css_class: str = "") -> str:
    paths = ICON_PATHS.get(name)
    if paths is None:
        return ""
    filled = name in FILLED_ICONS
    return format_html(
        '<svg xmlns="http://www.w3.org/2000/svg" width="{0}" height="{0}" viewBox="0 0 24 24" fill="{3}" '
        'stroke="{4}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" '
        'class="icon {1}" aria-hidden="true">{2}</svg>',
        size,
        css_class,
        mark_safe(paths),
        "currentColor" if filled else "none",
        "none" if filled else "currentColor",
    )
